"""Python API for applications (e.g. the SimHeart user interface).

Plain functions that return NumPy arrays; no UI framework is imported. Everything is read
from a *model bundle* folder written by ``scripts/export_models.py``:

    manifest.json        which generators exist, their default seed, provenance, notices
    generators/*.pt      generator weights only (<model>_<class>_s<seed>.pt)
    simulator.npz        per-class slider presets and ranges from the fitted parameters
    real_examples.npz    a sample of real validation beats per class, for comparison

Typical use::

    from simheart import api
    api.set_model_dir("exports/simheart-models")      # once, if not the default location
    beats = api.generate("V", n=8)                    # SimDCGAN, the bundle's default seed
    params = api.preset("V")                          # slider starting values
    params["R"]["b"] *= 1.5                           # "what if the QRS were wider?"
    simulated = api.simulate(params)
    fitted = api.calibrate(api.real_examples("V", 1).values[0])

**Synthetic beats are research artefacts, not real patient data.** Every result says what
it is (``Beats.source`` and ``Beats.synthetic``); show ``SYNTHETIC_NOTICE`` with them.
"""

import functools
import json
import math
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np
import torch

from simheart.data.scaling import minmax_to_sim_range, unit_to_sim
from simheart.models.gan import NOISE_DIM, Generator
from simheart.simulator.ecgsyn import (
    A_ROW,
    B_ROW,
    MCSHARRY_PARAMS,
    THETA_ROW,
    TYPICAL_PARAMS,
    WAVES,
    EcgSyn,
)
from simheart.simulator.fitting import ParamSpace, fit_beats

SYNTHETIC_NOTICE = (
    "Synthetic heartbeat generated by SimHeart for research and teaching. "
    "Not real patient data and not for clinical use."
)
MODELS: tuple[str, ...] = ("simdcgan", "dcgan")
BEAT_TYPES: tuple[str, ...] = ("S", "V", "F")
SAMPLING_RATE = 360
R_PEAK_INDEX = 72
TIME_MS = (np.arange(216) - R_PEAK_INDEX) / SAMPLING_RATE * 1000
_FIELDS = {"a": A_ROW, "b": B_ROW, "theta_deg": THETA_ROW}

_model_dir = Path(__file__).resolve().parents[2] / "exports" / "simheart-models"


@dataclass
class Beats:
    """A batch of beats ready to plot: ``values[i]`` against ``time_ms``."""

    values: np.ndarray  # [n, 216], scaled amplitude (same scale as the real beats)
    beat_type: str
    source: str  # "simdcgan", "dcgan", "simulator" or "real"
    synthetic: bool
    time_ms: np.ndarray = field(default_factory=lambda: TIME_MS.copy())
    info: dict = field(default_factory=dict)


@dataclass(frozen=True)
class ModelInfo:
    model: str
    beat_type: str
    seed: int
    is_default: bool


# --- model bundle -------------------------------------------------------------------------


def set_model_dir(path: str | Path) -> None:
    """Use the model bundle in ``path`` from now on (clears cached models)."""
    global _model_dir
    _model_dir = Path(path)
    _manifest.cache_clear()
    _generator.cache_clear()
    _simulator_tables.cache_clear()


def model_dir() -> Path:
    return _model_dir


def _require(path: Path) -> Path:
    if not path.exists():
        raise FileNotFoundError(
            f"{path} not found. Point the API at a model bundle with set_model_dir(), or "
            "create one with scripts/export_models.py."
        )
    return path


@functools.cache
def _manifest() -> dict:
    return json.loads(_require(_model_dir / "manifest.json").read_text(encoding="utf-8"))


@functools.cache
def _generator(model: str, beat_type: str, seed: int) -> Generator:
    path = _require(_model_dir / "generators" / f"{model}_{beat_type}_s{seed}.pt")
    net = Generator()
    net.load_state_dict(torch.load(path, map_location="cpu", weights_only=True))
    return net.eval()


@functools.cache
def _simulator_tables() -> dict[str, np.ndarray]:
    with np.load(_require(_model_dir / "simulator.npz")) as data:
        return {key: data[key] for key in data.files}


@functools.cache
def _sim() -> EcgSyn:
    return EcgSyn()


def available_models() -> list[ModelInfo]:
    """Every generator in the bundle, with whether it is the default for its class."""
    return [
        ModelInfo(m["model"], m["beat_type"], m["seed"], m["is_default"])
        for m in _manifest()["models"]
    ]


def _default_seed(model: str, beat_type: str) -> int:
    for info in available_models():
        if info.model == model and info.beat_type == beat_type and info.is_default:
            return info.seed
    raise ValueError(f"No {model} generator for class {beat_type!r} in {_model_dir}")


def _check(beat_type: str, model: str | None = None) -> None:
    if beat_type not in BEAT_TYPES:
        raise ValueError(f"beat_type must be one of {BEAT_TYPES}, got {beat_type!r}")
    if model is not None and model not in MODELS:
        raise ValueError(f"model must be one of {MODELS}, got {model!r}")


# --- parameters as readable dictionaries ------------------------------------------------------


def params_to_dict(params: np.ndarray | torch.Tensor) -> dict[str, dict[str, float]]:
    """[3, 5] parameters -> {"P": {"a": ..., "b": ..., "theta_deg": ...}, ...}."""
    p = np.asarray(params, dtype=np.float64)
    return {
        wave: {
            "a": float(p[A_ROW, w]),
            "b": float(p[B_ROW, w]),
            "theta_deg": math.degrees(p[THETA_ROW, w]),
        }
        for w, wave in enumerate(WAVES)
    }


def dict_to_params(params: dict[str, dict[str, float]]) -> torch.Tensor:
    """Inverse of ``params_to_dict``: -> [3, 5] float32 tensor (angles in radians)."""
    out = torch.zeros(3, 5)
    for w, wave in enumerate(WAVES):
        for name, row in _FIELDS.items():
            value = params[wave][name]
            out[row, w] = math.radians(value) if name == "theta_deg" else value
    return out


def preset(beat_type: str) -> dict[str, dict[str, float]]:
    """Slider starting values: the median fitted parameters of the class."""
    _check(beat_type)
    return params_to_dict(_simulator_tables()[f"{beat_type}_median"])


def slider_ranges(beat_type: str) -> dict[str, dict[str, tuple[float, float]]]:
    """(low, high) per parameter: the 1st-99th percentile of the class's fitted values."""
    _check(beat_type)
    low = params_to_dict(_simulator_tables()[f"{beat_type}_p01"])
    high = params_to_dict(_simulator_tables()[f"{beat_type}_p99"])
    return {wave: {name: (low[wave][name], high[wave][name]) for name in _FIELDS} for wave in WAVES}


# --- beats -----------------------------------------------------------------------------------


def generate(
    beat_type: str,
    n: int = 8,
    model: str = "simdcgan",
    seed: int | None = None,
    random_state: int | None = None,
) -> Beats:
    """Synthetic beats from a trained generator (``seed`` = which training run; None = default).

    Beats are rescaled one by one exactly like real beats and the synthetic datasets.
    ``random_state`` makes the output reproducible.
    """
    _check(beat_type, model)
    seed = _default_seed(model, beat_type) if seed is None else seed
    generator = None if random_state is None else torch.Generator().manual_seed(random_state)
    noise = torch.randn(n, NOISE_DIM, generator=generator)
    with torch.no_grad():
        made = unit_to_sim(_generator(model, beat_type, seed)(noise).squeeze(1)).numpy()
    return Beats(
        values=minmax_to_sim_range(made),
        beat_type=beat_type,
        source=model,
        synthetic=True,
        info={"seed": seed, "notice": SYNTHETIC_NOTICE},
    )


def simulate(params: dict[str, dict[str, float]], z0: float = 0.0, beat_type: str = "") -> Beats:
    """The raw ECGSYN beat for the given parameters (simulator units, not rescaled).

    Not rescaled on purpose: a slider that raises a wave's amplitude must show a taller
    wave. Simulator units are on the same scale as the real and generated beats.
    """
    with torch.no_grad():
        values = _sim()(dict_to_params(params)[None], z0).numpy()
    return Beats(
        values=values,
        beat_type=beat_type,
        source="simulator",
        synthetic=True,
        info={"params": params, "z0": z0, "notice": SYNTHETIC_NOTICE},
    )


def real_examples(beat_type: str, n: int = 8, random_state: int | None = None) -> Beats:
    """Real validation beats of the class (never used for training) for side-by-side display."""
    _check(beat_type)
    with np.load(_require(_model_dir / "real_examples.npz")) as data:
        beats, records = data[f"{beat_type}_X"], data[f"{beat_type}_record"]
    index = np.random.default_rng(random_state).choice(len(beats), size=min(n, len(beats)),
                                                        replace=False)  # fmt: skip
    return Beats(
        values=beats[index],
        beat_type=beat_type,
        source="real",
        synthetic=False,
        info={"records": records[index].tolist(), "split": "validation",
              "attribution": _manifest().get("data_attribution", "")},
    )  # fmt: skip


def calibrate(beat: np.ndarray, steps: int = 300) -> dict:
    """Fit simulator parameters to one beat [216] ("patient calibration").

    Returns {"params": readable dict, "z0": float, "r2": float}. Feed ``params`` (after
    changing a value, for "what-if" beats) to ``simulate``. More ``steps`` fit more closely
    but take longer. Measured on CPU for real V beats: 300 steps take about 3 s (R² 0.90-0.96),
    600 steps about 5 s (R² 0.96-0.98).
    """
    beats = torch.as_tensor(np.asarray(beat, dtype=np.float32)).reshape(1, -1)
    space = ParamSpace(
        float(_simulator_tables()["b_min"]), float(_simulator_tables()["theta_r_max"])
    )
    starts = torch.stack([*TYPICAL_PARAMS.values(), MCSHARRY_PARAMS])
    result = fit_beats(_sim(), beats, starts, space, steps=steps, lr=0.03)
    return {
        "params": params_to_dict(result.params[0]),
        "z0": float(result.z0[0]),
        "r2": float(result.r2[0]),
    }


# --- writing bundles (used by scripts/export_models.py and the tests) --------------------------


def write_bundle(
    out_dir: str | Path,
    generators: dict[tuple[str, str, int], dict],
    default_seeds: dict[tuple[str, str], int],
    fitted_params: dict[str, np.ndarray],
    space: ParamSpace,
    real_beats: dict[str, tuple[np.ndarray, np.ndarray]],
    provenance: dict | None = None,
) -> Path:
    """Write a model bundle.

    * generators:    (model, class, seed) -> generator state dict
    * default_seeds: (model, class) -> the seed ``generate`` uses by default
    * fitted_params: class -> accepted fitted parameters [N, 3, 5] (presets and ranges)
    * real_beats:    class -> (validation beats [M, 216] rescaled, their record IDs)
    """
    out = Path(out_dir)
    (out / "generators").mkdir(parents=True, exist_ok=True)
    models = []
    for (model, beat_type, seed), state in sorted(generators.items()):
        torch.save(state, out / "generators" / f"{model}_{beat_type}_s{seed}.pt")
        models.append({
            "model": model, "beat_type": beat_type, "seed": seed,
            "is_default": default_seeds.get((model, beat_type)) == seed,
        })  # fmt: skip
    tables: dict[str, np.ndarray] = {
        "b_min": np.array(space.b_min),
        "theta_r_max": np.array(space.theta_r_max),
    }
    for beat_type, params in fitted_params.items():
        tables[f"{beat_type}_median"] = np.median(params, axis=0)
        tables[f"{beat_type}_p01"] = np.percentile(params, 1, axis=0)
        tables[f"{beat_type}_p99"] = np.percentile(params, 99, axis=0)
    np.savez(out / "simulator.npz", **tables)
    examples: dict[str, np.ndarray] = {}
    for beat_type, (beats, records) in real_beats.items():
        examples[f"{beat_type}_X"] = beats.astype(np.float32)
        examples[f"{beat_type}_record"] = np.asarray(records)
    np.savez_compressed(out / "real_examples.npz", **examples)
    manifest = {
        "models": models,
        "notice": SYNTHETIC_NOTICE,
        "data_attribution": (
            "Real example beats: MIT-BIH Arrhythmia Database (Moody & Mark, 2001), "
            "PhysioNet (Goldberger et al., 2000), ODC Attribution License."
        ),
        **(provenance or {}),
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return out
